import { mkdirSync } from "node:fs";
import { unlink } from "node:fs/promises";
import path from "node:path";
import { randomUUID } from "node:crypto";
import multer from "multer";
import { env } from "../../config/env.js";
import { badRequest } from "../../lib/errors.js";

export const UPLOAD_ROOT = path.resolve(env.UPLOAD_DIR);
mkdirSync(UPLOAD_ROOT, { recursive: true });

const ALLOWED = new Map([
  ["image/jpeg", ".jpg"],
  ["image/png", ".png"],
  ["image/webp", ".webp"],
  ["application/pdf", ".pdf"],
]);

/**
 * Optional single attachment on ticket creation (e.g. photos of a misprint).
 * Stored on local disk under a random name; the original name is kept in the DB
 * and only used for the download filename. Production would use object storage
 * (S3/R2) with signed URLs behind the same service function.
 */
export const attachmentUpload = multer({
  storage: multer.diskStorage({
    destination: UPLOAD_ROOT,
    filename: (_req, file, cb) => cb(null, `${randomUUID()}${ALLOWED.get(file.mimetype) ?? ""}`),
  }),
  limits: { fileSize: 5 * 1024 * 1024, files: 1 },
  fileFilter: (_req, file, cb) => {
    if (ALLOWED.has(file.mimetype)) cb(null, true);
    else cb(badRequest("Attachments must be JPG, PNG, WEBP or PDF"));
  },
});

export const removeUpload = (storageKey: string) => unlink(path.join(UPLOAD_ROOT, storageKey)).catch(() => undefined);

export const resolveUpload = (storageKey: string) => {
  const resolved = path.resolve(UPLOAD_ROOT, storageKey);
  // Defence in depth: the key is generated by us, but never serve outside the upload root.
  if (!resolved.startsWith(UPLOAD_ROOT + path.sep)) throw badRequest("Invalid attachment path");
  return resolved;
};
